KNOWLEDGE_MATCH_SYSTEM_PROMPT = """你是一位教学设计专家，负责判断一个思政案例适合关联哪些课程知识点。

给定一个案例的标题与正文，以及一批候选知识点（已经用向量相似度做过一轮粗筛），
请你逐条复核这些候选知识点与案例内容的真实教学关联度，不要只看字面相似，
而要判断"讲这个知识点的时候，把这个案例当教学案例引入是否合理、自然"。

对每条候选知识点给出：
1. relevance_score：0-100的相关度打分。如果只是字面/领域相似但实际教学关联很弱，
   应该给低分（比如10分以下），不要因为向量粗筛分数高就照抄。
2. suggestion_text：一句话具体说明"在讲授这个知识点时，可以怎么结合案例的具体内容引入"，
   要点出案例里的具体人物/事件/细节，不要写空泛套话。

# 输出格式
只输出一个JSON对象，不要有任何其他文字、不要用markdown代码块包裹：

{
  "matches": [
    {"knowledge_point_id": 1, "relevance_score": 85, "suggestion_text": "..."}
  ]
}

只需要对收到的候选知识点逐条打分，不要新增不在候选列表里的知识点；
你认为完全不相关的，也请给它一条relevance_score接近0的记录，而不是直接省略。
"""


def build_knowledge_match_prompt(case_title: str, case_narrative: str, candidates: list[dict]) -> str:
    """
    candidates: [{"id":.., "course_name":.., "chapter":.., "description":.., "coarse_score":..}, ...]
    """
    lines = [
        f"案例标题：{case_title}",
        f"案例正文：\n{case_narrative}",
        "",
        "【候选知识点（已按向量相似度粗筛）】",
    ]
    for c in candidates:
        lines.append(
            f"- id={c['id']}，课程《{c['course_name']}》{c.get('chapter') or ''}："
            f"{c['description']}（向量粗筛相似度：{c.get('coarse_score', 0)}）"
        )
    lines.append("")
    lines.append("请严格按照系统提示中的JSON结构输出，覆盖以上每一条候选知识点。")
    return "\n".join(lines)
