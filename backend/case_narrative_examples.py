ALL_EXAMPLES = [SANMING_EXAMPLE, JIAXING_EXAMPLE, SANDACHANGYI_EXAMPLE, MULANXI_EXAMPLE]


def get_examples_by_dimension(dimension: str | None, limit: int = 2, topic_hint: str = "") -> list[dict]:
    """按维度挑范文，匹配不到（或还不知道维度）就退化成"现有全部范文当通用文笔示范"。
    现在生成流程里"案例正文"这一步还不知道案例最终会判给哪个维度（维度是后面结构化字段
    那一步才由模型判断出来的），所以dimension大概率传None——这里保留按维度筛选的接口，
    等范文库按维度扩充之后，只要在事实提炼阶段加一个"初步维度判断"字段，就可以传真实
    dimension进来精确匹配，不用改这个函数。

    topic_hint: 可选的主题关键词提示（一般传事实骨架里的"主题"字段），当候选范文数量
    大于limit时，按关键词跟每篇范文"主题"字段的重合度重排序、优先挑最贴题的几篇。
    注意这里跟"只有已知dimension时才生效"不同——不管dimension是否为空（生产环境常态是
    None），只要传了topic_hint且候选数>1就会生效，这样dimension未知时也能优先选到
    主题相关的范文，而不是永远固定用候选列表里的前几篇。"""
    if dimension:
        matched = [e for e in ALL_EXAMPLES if e["dimension"] == dimension]
        if not matched:
            matched = ALL_EXAMPLES
    else:
        matched = ALL_EXAMPLES

    if topic_hint and len(matched) > 1:
        hint_words = [w for w in topic_hint.replace("、", " ").replace("，", " ").split() if w]

        def _score(ex):
            theme = ex["example_facts"].get("主题", "")
            return sum(1 for w in hint_words if w in theme)

        matched = sorted(matched, key=_score, reverse=True)

    return matched[:limit]
